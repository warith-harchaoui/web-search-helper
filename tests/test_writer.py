"""The written answer: the browser client's tests, and the plan's freshness.

The model ladder (assets/writer-plan.json) and the parity fixture
(tests/js/choose-fixture.json) are generated by best-engine-ai-helper, which
owns the choice. When best-engine is importable, both are checked against what
it would write now; the JavaScript twin of its `browser.choose` is checked
against the fixture by the Node tests.
"""

import json
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "src/web_search_helper/assets/writer-plan.json"
FIXTURE = ROOT / "tests/js/choose-fixture.json"


def test_node_tests_pass():
    node = shutil.which("node")
    if not node:
        pytest.skip("node not on PATH")
    out = subprocess.run(
        [node, "--test", str(ROOT / "tests/js/client.test.mjs")],
        capture_output=True,
        text=True,
        check=False,
    )
    assert out.returncode == 0, out.stdout[-3000:] + out.stderr[-2000:]


def test_plan_is_what_best_engine_writes_now():
    browser = pytest.importorskip("best_engine_ai_helper.browser")
    shipped = json.loads(PLAN.read_text(encoding="utf-8"))
    fresh = browser.plan(shipped["usage"], languages=shipped["languages"])
    for key in ("candidates", "policy", "transformers"):
        assert shipped[key] == fresh[key], f"writer-plan.json is stale ({key}): regenerate it"


def test_fixture_matches_best_engine():
    browser = pytest.importorskip("best_engine_ai_helper.browser")
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    for s in json.loads(FIXTURE.read_text(encoding="utf-8"))["scenarios"]:
        r = browser.choose(plan, s["device"])
        rung = f"{r['candidate']['model']}|{r['candidate']['dtype']}" if r["candidate"] else None
        assert {"rung": rung, "reason": r["reason"], "seconds": r["seconds"]} == s["expected"]


def test_plan_shape():
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    assert plan["usage"] == "rag-answer" and plan["runtime"] == "transformers.js"
    assert {"fr", "en"} <= set(plan["languages"])
    for c in plan["candidates"]:
        assert c["files"] and all(u.startswith("https://huggingface.co/") for u in c["files"])
        assert c["loader"] in {"processor", "tokenizer"}
